package com.shaivikagroups.lms.practice;

import jakarta.persistence.*;
import java.time.Instant;

@Entity
@Table(name = "practice_drafts")
public class PracticeDraftEntity {

    @Id
    @Column(name = "id", length = 64, nullable = false)
    private String id;

    @Column(name = "tenant_id", length = 64, nullable = false)
    private String tenantId;

    @Column(name = "user_id", length = 64, nullable = false)
    private String userId;

    @Column(name = "problem_id", length = 64, nullable = false)
    private String problemId;

    @Column(name = "language", length = 32, nullable = false)
    private String language;

    @Column(name = "code", columnDefinition = "text", nullable = false)
    private String code;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt = Instant.now();

    public PracticeDraftEntity() {}

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getTenantId() {
        return tenantId;
    }

    public void setTenantId(String tenantId) {
        this.tenantId = tenantId;
    }

    public String getUserId() {
        return userId;
    }

    public void setUserId(String userId) {
        this.userId = userId;
    }

    public String getProblemId() {
        return problemId;
    }

    public void setProblemId(String problemId) {
        this.problemId = problemId;
    }

    public String getLanguage() {
        return language;
    }

    public void setLanguage(String language) {
        this.language = language;
    }

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Instant updatedAt) {
        this.updatedAt = updatedAt;
    }
}

